#!/usr/bin/env python3
"""Regenerate the conservative, public PWA page allowlist from the PHP catalog.
Run after adding/removing tools; always review ONLINE_ONLY exclusions first.
"""
from pathlib import Path
import re, json
root=Path(__file__).resolve().parents[1]
source=(root/'includes/tools-catalog.php').read_text(encoding='utf-8')
tools=re.findall(r"'href'\s*=>\s*'([^']+)'",source)
assert len(tools)>=38 and len(tools)==len(set(tools))
# Login/db and server-processing workflows are explicitly never snapshotted.
excluded={
 'kena-sxoleion-login.php': 'Σύνδεση χρηστών / προσωπικά δεδομένα',
 'ypologismos-didaktikon-anagkon.php': 'Περιλαμβάνει υποβολή (POST) και λειτουργίες διακομιστή',
}
# Public read-only guidance that isn't linked as a separate catalogue tool.
supplement=[
 'ergaleia.php',
 'ypologismos-morion-metathesis-protovathmia.php',
 'prothesmies.php',
 'adeies-monimon.php',
 'adeies-anapliroton.php',
 'adeies-sygkrisi.php',
 'nomiki-epikairotita.php',
]
for path in tools+supplement:
 assert re.fullmatch(r'[a-z0-9-]+\.php',path),path
 assert (root/path).is_file(),path
pages=list(dict.fromkeys(supplement+[p for p in tools if p not in excluded]))
output='''/* GENERATED by tools/build-offline-registry.py — publicly readable pages only.\n * These are offline SNAPSHOTS, not guarantees that every external link works.\n * Never add login, admin, API, POST, personal or database-dependent pages.\n */\nself.EDU_OFFLINE_REGISTRY = Object.freeze({\n  version: '3.22.204',\n  pages: Object.freeze('''+json.dumps(pages,ensure_ascii=False,indent=4)+'''),\n  excluded: Object.freeze('''+json.dumps(excluded,ensure_ascii=False,indent=4)+''')\n});\n'''
(root/'assets/offline-registry.js').write_text(output,encoding='utf-8')
print(f'{len(tools)} catalog tools, {len(pages)} public snapshots incl. supplements, {len(excluded)} excluded')
