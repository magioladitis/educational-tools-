        'Νεοελληνική Λογοτεχνία' => array('Α΄', 'Β΄', 'Γ΄'),
        'Αρχαία Ελληνική Γλώσσα' => array('Α΄', 'Β΄', 'Γ΄'),
        'Αρχαία Ελληνικά Κείμενα από Μετάφραση' => array('Α΄', 'Β΄', 'Γ΄'),
        'Μαθηματικά' => array('Α΄', 'Β΄', 'Γ΄'),
        'Φυσική' => array('Α΄', 'Β΄', 'Γ΄'),
        'Χημεία' => array('Β΄', 'Γ΄'),
        'Βιολογία' => array('Α΄', 'Β΄', 'Γ΄'),
        'Γεωλογία-Γεωγραφία' => array('Α΄', 'Β΄'),
        'Ιστορία' => array('Α΄', 'Β΄', 'Γ΄'),
        'Κοινωνική και Πολιτική Αγωγή' => array('Γ΄'),
        'Οικονομικά' => array('Γ΄'),
        'Θρησκευτικά' => array('Α΄', 'Β΄', 'Γ΄'),
        'Ηθική' => array('Α΄', 'Β΄', 'Γ΄'),
        'Αγγλικά' => array('Α΄', 'Β΄', 'Γ΄'),
        '2η Ξένη Γλώσσα (Γαλλικά / Γερμανικά / Ιταλικά)' => array('Α΄', 'Β΄', 'Γ΄'),
        'Πληροφορική' => array('Α΄', 'Β΄', 'Γ΄'),
        'Φυσική Αγωγή' => array('Α΄', 'Β΄', 'Γ΄'),
    );

    foreach ($dayGeneralRows as $row) {
        if ($row['school'] === 'gymnasio' && isset($specialGymGrades[$row['subject']])) {
            foreach (array('kallitexniko_gymnasio', 'mousiko_gymnasio') as $targetSchool) {
                $copy = $row;
                $copy['school'] = $targetSchool;
                $copy['grades'] = $specialGymGrades[$row['subject']];
                $copy['section'] = $row['section'] !== ''
                    ? 'Μαθήματα Γενικής Παιδείας · ' . $row['section']
                    : 'Μαθήματα Γενικής Παιδείας';

                /* Τα ειδικά ωρολόγια ΦΕΚ Β΄ 2104/2026 (Καλλιτεχνικό)
                 * και Β΄ 2107/2026 (Μουσικό) προβλέπουν μόνο Γαλλικά ή
                 * Γερμανικά. Η Ιταλική του γενικού Γυμνασίου (ΠΕ34) δεν
                 * αποτελεί επιλογή στις δύο ειδικές δομές. */
                if (strpos($row['subject'], '2η Ξένη Γλώσσα') === 0) {
                    $copy['subject'] = 'Γαλλικά / Γερμανικά';
                    $copy['A'] = array('ΠΕ05', 'ΠΕ07');
                    unset($copy['B'], $copy['C'], $copy['B_notes'], $copy['C_notes']);
                    $copy['note'] = 'Στο ισχύον ειδικό ωρολόγιο προβλέπονται μόνο Γαλλικά ή Γερμανικά.';
                }

                $rows[] = $copy;
            }
        }

        if ($row['school'] === 'gymnasio' && $row['subject'] === 'Καλλιτεχνικά') {
            $copy = $row;
            $copy['school'] = 'mousiko_gymnasio';
            $copy['grades'] = array('Α΄', 'Β΄', 'Γ΄');
            $copy['section'] = 'Μαθήματα Γενικής Παιδείας · Αισθητική Αγωγή';
            $rows[] = $copy;
        }

        if ($row['school'] === 'gel'
            && strpos($row['subject'], '2η Ξένη Γλώσσα') !== 0) {
            foreach (array('kallitexniko_gel', 'mousiko_gel') as $targetSchool) {
                $copy = $row;
                $copy['school'] = $targetSchool;
                if (strpos($row['section'], 'Μαθήματα Γενικής Παιδείας') !== 0) {
                    $copy['section'] = $row['section'] !== ''
                        ? 'Μαθήματα Γενικής Παιδείας · ' . $row['section']
                        : 'Μαθήματα Γενικής Παιδείας';
                }
                $rows[] = $copy;
            }
        }
    }

    /*
     * Γυμνάσια και Λύκεια Ε.Α.Ε.
     * Πηγή: Υ.Α. 72559/Δ3, ΦΕΚ Β΄ 3275/11-06-2026.
     * Οι πίνακες του Λυκείου Ε.Α.Ε. αντιστοιχούν στα μαθήματα/αναθέσεις του
     * ΓΕΛ της ίδιας απόφασης. Στο Γυμνάσιο Ε.Α.Ε. δεν περιλαμβάνεται 2η ξένη
     * γλώσσα, γι’ αυτό η συγκεκριμένη γραμμή δεν αντιγράφεται.
     */
    $generalRows = array_filter($rows, function ($row) {
        return $row['school'] === 'gymnasio' || $row['school'] === 'gel';
    });
    foreach ($generalRows as $row) {
        if ($row['school'] === 'gymnasio') {
            if (strpos($row['subject'], '2η Ξένη Γλώσσα') === 0) {
                continue;
            }
            $copy = $row;
            $copy['school'] = 'eae_gymnasio';
            $rows[] = $copy;
        } elseif ($row['school'] === 'gel') {
            $copy = $row;
            $copy['school'] = 'eae_lykeio';
            $rows[] = $copy;
        }
    }

    /* Φορτώνουμε κάθε dataset σε απομονωμένο function scope ώστε το τοπικό
     * $rows ενός include να μην μπορεί να αντικαταστήσει το κεντρικό dataset. */
    foreach (array(
        'teaching-assignments-eneegyl.php',
        'teaching-assignments-eneegyl-d.php',
        'teaching-assignments-kallitexnika.php',
        'teaching-assignments-epal.php',
        'teaching-assignments-pepal.php',
        'teaching-assignments-mousika.php'
    ) as $assignmentFile) {
        $extraRows = teachingAssignmentsLoadRows(__DIR__ . '/' . $assignmentFile);
        if ($extraRows) {
            $rows = array_merge($rows, $extraRows);
        }
    }

    return $rows;
}

function teachingAssignmentKnownSpecialties()
{
    $codes = array();
    foreach (teachingAssignmentsData() as $row) {
        foreach (array('A', 'B', 'C', 'special_codes') as $level) {
            if (empty($row[$level]) || !is_array($row[$level])) {
                continue;
            }
            foreach ($row[$level] as $code) {
                $codes[$code] = true;
            }
        }
    }
    /* Οι συγκεντρωτικοί κωδικοί εμφανίζονται στους πίνακες του ΦΕΚ για να
     * δηλώσουν όλους τους υποκλάδους, αλλά δεν αποτελούν επιλογή ειδικότητας.
     * Οι υποκλάδοι εξακολουθούν να ταιριάζουν μέσω του codeMatches() του UI. */
    foreach (array('ΠΕ04', 'ΠΕ79', 'ΠΕ87', 'ΠΕ88', 'ΠΕ89', 'ΠΕ91', 'ΤΕ') as $umbrellaCode) {
        unset($codes[$umbrellaCode]);
    }

    $result = array_keys($codes);
    natcasesort($result);
    return array_values($result);
}
