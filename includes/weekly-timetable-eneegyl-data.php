function weeklyTimetableEneegylDisplayHoursTotal($display)
{
    $clean = preg_replace('/\\([^)]*\\)/u', '', (string) $display);
    preg_match_all('/(\\d+)\\s*(?:Θ|Ε|Σ)/u', $clean, $matches);

    $sum = 0;
    foreach ($matches[1] as $value) {
        $sum += (int) $value;
    }

    return $sum;
}

