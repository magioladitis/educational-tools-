/* Shared transfer-locality supporting documents, 2026–27.
 * The school/area eligibility assessment remains grade- and route-specific.
 * No certificate is submitted or retrieved by this advisory component.
 */
(function(global){
'use strict';
function guide(grade){
 var authority=grade==='primary'?'ΔΠΕ':'ΔΔΕ';
 return 'Για την απόδειξη της εντοπιότητας απαιτείται πιστοποιητικό γέννησης ή πιστοποιητικό οικογενειακής κατάστασης. '+
  'Η αρμόδια '+authority+' το αναζητά αυτεπαγγέλτως όπου προβλέπεται· προσκομίστε το μόνο αν σας ζητηθεί από την Υπηρεσία.\n'+
  'Το πιστοποιητικό πρέπει να αναγράφει υποχρεωτικά την ημερομηνία κτήσης δημοτικότητας. '+
  'Πρέπει να προκύπτει ότι είστε δημότης Δήμου ή Κοινότητας της ζητούμενης περιοχής επί τουλάχιστον δύο έτη έως την ημέρα υποβολής της αίτησης μετάθεσης. '+
  'Η μόνιμη διαμονή μόνη της δεν αρκεί.\n'+
  'Ελέγξτε την αντιστοίχιση με τη ζητούμενη περιοχή μετάθεσης ή, σε βελτίωση/οριστική τοποθέτηση, με τον Δήμο όπου λειτουργεί το συγκεκριμένο σχολείο. '+
  'Για μετάθεση μεταξύ περιοχών επιτρέπεται αθροιστικός υπολογισμός διετίας σε διαφορετικούς Δήμους της ίδιας περιοχής· δεν ισχύει για μετακινήσεις μεταξύ σχολείων της ίδιας περιοχής.';
}
function source(grade){
 return 'παρ. 9 άρθρου 16 π.δ. 50/1996 (ΦΕΚ Α΄ 45), όπως ισχύει· '+
  'εγκύκλιος '+(grade==='primary'?'Πρωτοβάθμιας 138023/Ε2':'Δευτεροβάθμιας 138014/Ε2')+
  '/15-10-2026, Μέρος Δεύτερο, Κεφ. Ε΄ — Εντοπιότητα.';
}
function summary(grade){
 return 'Πιστοποιητικό γέννησης ή οικογενειακής κατάστασης (αυτεπάγγελτα από '+(grade==='primary'?'ΔΠΕ':'ΔΔΕ')+' όπου προβλέπεται): ελέγξτε ημερομηνία κτήσης δημοτικότητας και συμπληρωμένη διετία.';
}
global.EducationTransferLocalityResources=Object.freeze({detail:guide,source:source,summary:summary});
})(window);
