ck('Onaseia uses AsepPeAcademic.calculate', 'AsepPeAcademic.calculate("asepPeAcademic")' in o)
ck('general has no local syncComputerUI', 'function syncComputerUI' not in g)
ck('Onaseia has no local calculateDetailedAcademic', 'function calculateDetailedAcademic' not in o)
ck('general has no direct EducationAcademic.calculate', 'EducationAcademic.calculate(' not in g)
ck('Onaseia has no direct EducationAcademic.calculate', 'EducationAcademic.calculate(' not in o)
ck('general has no direct AsepLanguageSelector.calculate', 'AsepLanguageSelector.calculate(' not in g)
ck('Onaseia has no direct AsepLanguageSelector.calculate', 'AsepLanguageSelector.calculate(' not in o)
ck('shared component owns language selector', 'renderAsepLanguageSelector(' in c)
ck('shared component owns computer proof', 'renderAsepComputerProof(' in c)
ck('shared component owns training proof', 'renderTrainingProof(' in c)
ck('shared controller owns PE86 UI exclusion', "specialty==='ΠΕ86'" in j or "specialty === 'ΠΕ86'" in j)
ck('shared controller delegates scoring to EducationAcademic', 'EducationAcademic.calculate' in j)
