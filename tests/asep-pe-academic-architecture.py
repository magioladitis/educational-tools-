from pathlib import Path
root=Path(__file__).resolve().parents[1]
g=(root/'ypologismos-morion.php').read_text()
o=(root/'ypologismos-morion-onaseia.php').read_text()
c=(root/'includes/components/asep-pe-academic.php').read_text()
