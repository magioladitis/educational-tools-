ck('Onaseia still keeps manual mode UI', 'name="academicMode" value="manual"' in o)
ck('Onaseia detailed block remains separate from manual wrapper', 'id="detailedAcademic"' in o and 'id="manualAcademic"' in o)
ck('general loads shared controller before inline code', g.index('includes/asep-pe-academic.js') < g.index('<script>\n  let lastResultText'))
ck('Onaseia loads shared controller before inline code', o.index('includes/asep-pe-academic.js') < o.index('<script>\n  let isLiveCalculation'))
ck('shared component is presentation-only re scoring engine', 'Scoring remains exclusively' in c)
passed=sum(v for _,v in checks)
for name,v in checks: print(('✓ ' if v else '✗ ')+name)
print(f'\nPASS: {passed}')
print(f'FAIL: {len(checks)-passed}')
if passed!=len(checks): raise SystemExit(1)
