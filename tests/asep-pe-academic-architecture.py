ck('general requires shared PE academic component', 'asep-pe-academic.php' in g)
ck('Onaseia requires shared PE academic component', 'asep-pe-academic.php' in o)
ck('general renders shared PE academic component', 'renderAsepPeAcademic(' in g)
ck('Onaseia renders shared PE academic component', 'renderAsepPeAcademic(' in o)
