/* New intercultural transfer procedure — circular 138014/E2/15-10-2026, Chapter Z. */
'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
const root=path.resolve(__dirname,'..');
const ctx={window:{},Number,String,Math,Array,Object};
ctx.window.window=ctx.window;
vm.runInNewContext(fs.readFileSync(path.join(root,'includes/transfer-eligibility.js'),'utf8'),ctx);
const m=ctx.window.EducationTransferEligibility;
const good={organic:'yes',current:'no',vacancy:'yes',languageCase:'usual'};
function check(label,predicate){assert.ok(predicate,label);}
check('nine numbered qualifications',m.INTERCULTURAL_QUALIFICATIONS.length===9);
check('language first',m.INTERCULTURAL_QUALIFICATIONS[0].id==='origin_language');
check('seminars last',m.INTERCULTURAL_QUALIFICATIONS[8].id==='seminars');
check('no score property',!Object.prototype.hasOwnProperty.call(m.intercultural(good),'points'));
check('qualifiers not mandatory',m.intercultural(good).verdict==='preliminary_met');
check('missing organizational service denied',m.intercultural({...good,organic:'no'}).verdict==='not_established');
check('unknown organizational service review',m.intercultural({...good,organic:'unknown'}).verdict==='needs_verification');
check('below two years denied',m.intercultural({...good,current:'yes',years:1.5}).verdict==='not_established');
check('two years preliminary',m.intercultural({...good,current:'yes',years:2}).verdict==='preliminary_met');
check('invalid years review',m.intercultural({...good,current:'yes',years:''}).verdict==='needs_verification');
check('unknown previously in intercultural review',m.intercultural({...good,current:'unknown'}).verdict==='needs_verification');
check('no vacancy denied',m.intercultural({...good,vacancy:'no'}).verdict==='not_established');
check('unknown vacancy review',m.intercultural({...good,vacancy:'unknown'}).verdict==='needs_verification');
check('majority roma language exception',m.intercultural({...good,languageCase:'roma'}).languageException===true);
check('selected qualifications validated',m.intercultural({...good,qualifications:['greek_second','bogus']}).selectedQualifications.length===1);
check('2021 reusable dossier',m.dossier({kind:'intercultural',year:'2021',newElements:false}).skipResubmission);
check('2026 reusable dossier',m.dossier({kind:'intercultural',year:'2026',newElements:false}).skipResubmission);
check('2020 not reusable',!m.dossier({kind:'intercultural',year:'2020',newElements:false}).skipResubmission);
check('new items require action',!m.dossier({kind:'intercultural',year:'2025',newElements:true}).skipResubmission);
const php=fs.readFileSync(path.join(root,'ypologismos-morion-metathesis.php'),'utf8');
const ui=fs.readFileSync(path.join(root,'includes/transfer-ui.js'),'utf8');
const doc=fs.readFileSync(path.join(root,'includes/transfer-documents.js'),'utf8');
check('mode option present',php.includes('<option value="intercultural">'));
check('panel exists',php.includes('id="transferInterculturalEligibility"'));
check('nine checkbox options', (php.match(/data-intercultural-qual=/g)||[]).length===9);
check('eligibility panel in UI',ui.includes("mode==='intercultural'"));
check('qualification scoring hidden',ui.includes("input.mode === 'intercultural'"));
check('intercultural checklist',doc.includes('function interculturalDocuments()'));
check('intercultural checklist invoked',doc.includes("mode==='intercultural'"));
check('portal reference retained in consolidated disclosure',doc.includes('mydocs.minedu.gov.gr') && php.includes('transferSubmissionGuidanceBody'));
console.log('PASS: 25 intercultural transfer tests');
