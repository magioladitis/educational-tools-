'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const vacancies=require('../includes/transfer-primary-intercultural-vacancies.js');
const php=fs.readFileSync(path.join(root,'ypologismos-morion-metathesis-protovathmia.php'),'utf8');
const js=fs.readFileSync(path.join(root,'includes/transfer-primary.js'),'utf8');
let checks=0;
function check(value,description){assert.ok(value,description);checks++;}
check(vacancies.level==='ΠΕ'&&vacancies.year==='2026–2027','primary annual dataset');
check(vacancies.rows.length===9,'nine original Excel records');
check(vacancies.totalVacancies===16&&vacancies.totalSchools===6,'16 distinct vacancies across six schools');
check(new Set(vacancies.rows.map(x=>x.school)).size===6,'six school names');
check(vacancies.rows.reduce((sum,row)=>sum+row.vacancies,0)===16,'row totals');
check(JSON.stringify(vacancies.reportGroups)===JSON.stringify({'ΠΕ06':1,'ΠΕ11':2,'ΠΕ70+ΠΕ71':13}),'three original groups');
check(vacancies.branches().length===4,'four individual codes in selector, only three distinct groups');
check(vacancies.branches().filter(x=>x.shared).length===2,'shared groups flagged');
check(vacancies.schoolsForBranch('ΠΕ70').length===6&&vacancies.schoolsForBranch('ΠΕ71').length===6,'both codes expose shared schools');
check(vacancies.schoolsForBranch('ΠΕ70').reduce((n,x)=>n+x.vacancies,0)===13,'PE70 group is 13 shared positions');
check(vacancies.schoolsForBranch('ΠΕ71').reduce((n,x)=>n+x.vacancies,0)===13,'PE71 group same 13 shared positions not additional');
check(vacancies.schoolsForBranch('ΠΕ06').length===1&&vacancies.schoolsForBranch('ΠΕ11').length===2,'independent specialties');
check(vacancies.schoolsForBranch('ΠΕ60').length===0,'no false PE60 open positions');
check(vacancies.count('ΠΕ70',vacancies.rows.find(x=>x.school.includes('ΜΕΝΕΜΕΝΗΣ')).school)===2,'Menemeni joint group has 2 vacancies');
check(vacancies.rows.some(x=>x.language==='Αλβανική')&&vacancies.rows.some(x=>x.language==='Αγγλική'),'language metadata retained');
check(vacancies.rows.every(x=>x.directorate.startsWith('ΔΙΕΥΘΥΝΣΗ Π.Ε.')),'DPE names retained');
check(php.includes('id="primaryInterVacancyBranch"')&&php.includes('id="primaryInterVacancySchool"'),'two primary vacancy selectors');
check(php.includes("'id' => 'primaryMultipleApplicationsHelp'")&&php.includes('Κεφ. Ζ΄ §9'),'primary FAQ and legal reference');
check(php.includes('ΚΕΔΑΣΥ και περιοχές ΕΑΕ → Διαπολιτισμικά → από περιοχή σε περιοχή → αμοιβαίες'),'accurate processing order');
check(!php.includes('includes/transfer-intercultural-vacancies.js')&&php.includes('includes/transfer-primary-intercultural-vacancies.js'),'primary-only vacancy module');
check(js.includes('function updateInterculturalVacancies()')&&js.includes('ΚΟΙΝΑ κενά'),'dynamic UI explicitly signals shared positions');
check(js.includes('function updateInterculturalVacancies()')&&js.includes('updateInterculturalVacancies();'),'dynamic UI refresh wired');
check(!php.includes('includes/transfer-documents.js')&&!php.includes('includes/transfer-eligibility.js'),'secondary legal logic not imported');
console.log('PASS',checks,'primary vacancy, FAQ, grouped positions, separation regression assertions');
