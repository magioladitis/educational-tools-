'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'ypologismos-morion-metathesis.php'), 'utf8');
const css = fs.readFileSync(path.join(root, 'assets/common.css'), 'utf8');
const html = cp.execFileSync('php', ['ypologismos-morion-metathesis.php'], {cwd: root, encoding:'utf8'});
const clean = html.replace(/\s+/g, ' ');
assert.match(src, /'id'\s*=>\s*'transferDeadlines'/);
assert.match(src, /'summary_html'\s*=>\s*'Σημαντικές προθεσμίες: <strong>Αιτήσεις έως 02\/11\/2026<\/strong>'/);
assert.ok(!/<div class="transfer-deadlines"/.test(src), 'old static deadline box removed');
assert.match(clean, /<details id="transferDeadlines" class="edu-disclosure transfer-deadlines">/);
assert.doesNotMatch(clean, /<details id="transferDeadlines"[^>]*\bopen(?:\s|=|>)/);
assert.match(clean, /<summary class="edu-disclosure__summary"><span>Σημαντικές προθεσμίες: <strong>Αιτήσεις έως 02\/11\/2026<\/strong>/);
assert.ok(clean.includes('31/12/2026, ώρα 15:00'));
assert.ok(clean.includes('Η προσωρινή αποθήκευση δεν είναι οριστικοποίηση.'));
assert.ok(clean.includes('Αμοιβαίες μεταθέσεις:'));
assert.equal((clean.match(/id="transferDeadlines"/g) || []).length, 1);
assert.match(css, /\.edu-disclosure\.transfer-deadlines/);
console.log('PASS: v3.22.141 deadlines disclosure contract');
