'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const vm=require('node:vm'),window={};
vm.runInNewContext(fs.readFileSync(path.join(root,'includes/transfer-eligibility.js'),'utf8'),{window});
const eligibility=window.EducationTransferEligibility;
const page=fs.readFileSync(path.join(root,'ypologismos-morion-metathesis.php'),'utf8');
const ui=fs.readFileSync(path.join(root,'includes/transfer-ui.js'),'utf8');
const docs=fs.readFileSync(path.join(root,'includes/transfer-documents.js'),'utf8');
const q=['doctorate','masters','two_year','experience','pe11'];
let checks=0;function check(x,label){assert.ok(x,label);checks++;}
function eq(x,y,label){assert.equal(x,y,label);checks++;}
for(const key of q)check(page.includes('data-eae-qualification="'+key+'"'),'checkbox for '+key);
check(page.includes('id="transferEaeSensoryCertification"'),'sensory certification selection');
check(!page.includes('type="radio" name="eaeDocQualification"'),'no second qualification radio in PHP');
check(!docs.includes('eaeChoices('),'no duplicate qualification picker in docs');
check(docs.includes("chosen.indexOf('masters')!==-1"),'masters evidence conditional');
check(docs.includes("chosen.indexOf('experience')!==-1"),'experience evidence conditional');
check(ui.includes('data-eae-qualification]:checked'),'UI reads all checkboxes');
check(ui.includes("hasFiveYears"),'five-year field shown when chosen');
check(ui.includes('transferEaeSensoryCertificationRow'),'sensory selector context-aware');
const base={origin:'general',branch:'pe03',teachingYears:4,destination:'smeae'};
let r=eligibility.eae({...base,qualifications:['doctorate','masters']});
eq(r.verdict,'preliminary_met','two accepted routes are sufficient');
eq(r.selectedQualifications.length,2,'selected routes preserved');
eq(r.validQualifications.length,2,'both selected routes valid');
r=eligibility.eae({...base,qualifications:['masters','experience'],eaeYears:4});
eq(r.verdict,'needs_verification','extra invalid route not global red if masters valid');
check(r.review.some(t=>t.includes('πέντε')),'invalid extra route explained');
r=eligibility.eae({...base,qualifications:['experience'],eaeYears:4.9});
eq(r.verdict,'not_established','five-year-only route below five red');
r=eligibility.eae({...base,qualifications:['experience'],eaeYears:5});
eq(r.verdict,'preliminary_met','five-year-only route at five passes');
r=eligibility.eae({...base,qualifications:['pe11']});
eq(r.verdict,'not_established','PE11-only route not allowed for PE03');
r=eligibility.eae({...base,branch:'pe11',qualifications:['pe11']});
eq(r.verdict,'preliminary_met','PE11 specialty route passes subject to docs');
r=eligibility.eae({...base,qualifications:['masters'],destination:'deaf',sensoryCertification:'unknown'});
eq(r.verdict,'needs_verification','unknown EΝΓ needs verification');
r=eligibility.eae({...base,qualifications:['masters'],destination:'deaf',sensoryCertification:'no'});
eq(r.verdict,'not_established','declared absent EΝΓ blocks route');
r=eligibility.eae({...base,qualifications:['masters'],destination:'deaf',sensoryCertification:'yes'});
eq(r.verdict,'needs_verification','declared EΝΓ still needs certificate verification');
r=eligibility.eae({...base,qualifications:['masters'],destination:'blind',sensoryCertification:'no'});
eq(r.verdict,'not_established','declared absent Braille blocks route');
r=eligibility.eae({...base,qualifications:['masters'],teachingYears:2.9});
eq(r.verdict,'not_established','three-year service condition not relaxed');
r=eligibility.eae({...base,qualifications:[]});
eq(r.verdict,'needs_verification','no qualification review');
r=eligibility.eae({...base,qualification:'masters'});
eq(r.verdict,'preliminary_met','legacy single-route caller preserved');
console.log('PASS',checks,'3.22.144 EAE qualification contracts');
