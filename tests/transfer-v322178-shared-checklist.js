'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const base=path.resolve(__dirname,'..');
const read=(f)=>fs.readFileSync(path.join(base,f),'utf8');
const sandbox={window:{}};
vm.runInNewContext(read('includes/transfer-checklist.js'),sandbox);
const create=sandbox.window.EducationTransferChecklist.create;
assert.equal(typeof create,'function');
const primary=create(),secondary=create();
const pRows=[{id:'registry',action:false},{id:'children',action:true},{id:'coservice',action:true}];
const pAction=d=>d.action;
let p=primary.reconcile(pRows,pAction);
assert.equal(p.total,2);assert.equal(p.completed,0);
primary.set('children',true);
p=primary.reconcile(pRows,pAction);
assert.equal(p.completed,1);assert.equal(primary.isComplete('children'),true);
assert.equal(secondary.isComplete('children'),false,'one grade cannot share user state with the other');
assert.equal(primary.progressText(p,'primary'),'1 από 2 ενέργειες δικαιολογητικών έχουν ολοκληρωθεί');
primary.reconcile([{id:'registry',action:false},{id:'children',action:false}],pAction);
assert.equal(primary.isComplete('children'),false,'information-only entries clear old preparation state');
primary.set('coservice',true);
p=primary.reconcile([{id:'coservice',action:true},{id:'coservice',action:true}],pAction);
assert.equal(p.total,1,'duplicate ids cannot produce duplicate preparation totals');
assert.equal(p.completed,1);
p=primary.reconcile([],pAction);
assert.equal(p.total,0);assert.equal(primary.isComplete('coservice'),false,'removed docs are pruned');
secondary.set('__proto__',true);assert.equal(secondary.isComplete('__proto__'),true,'prototype names are safe in null-prototype dictionary');
secondary.reconcile([{id:'record',action:false},{id:'blocked',action:false}],d=>d.action);
assert.equal(secondary.isComplete('__proto__'),false);
assert.equal(secondary.progressText({total:0,completed:0},'secondary'),'Δεν προκύπτουν δικαιολογητικά προς προετοιμασία από τις επιλογές σας.');
secondary.set('yes',true);
assert.equal(secondary.progressText(secondary.reconcile([{id:'yes',action:true}],d=>d.action),'secondary'),'Δικαιολογητικά/ενέργειες που ετοιμάστηκαν: 1 από 1.');
