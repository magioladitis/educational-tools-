'use strict';
const fs = require('fs'), vm = require('vm'), path = require('path');
const assert = require('node:assert/strict');
const elements = {};
const val = (id, value) => {elements[id] = {value:String(value),checked:false}};
val('mode','local');val('serviceYears','0');val('serviceMonths','0');val('serviceDays','0');
val('eligibleChildren','0');val('msdMode','direct');val('msdDirectPoints','0');
for(const id of ['familyStatusEligible','coService','locality'])elements[id]={checked:false};
const document={getElementById(id){assert.ok(elements[id],`Missing ${id}`);return elements[id]},querySelectorAll(){return []}};
const window={};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../includes/transfer-documents.js'),'utf8'),{window,document});
const build = window.EducationTransferDocuments.build;
let checks=0;
function verify(cond,msg){assert.ok(cond,msg);checks++}
const byId = (rows,id) => rows.find(r=>r.id===id);
let rows = build();
verify(!byId(rows,'family'),'no family row without criterion');
verify(!byId(rows,'children-specific'),'no special child docs without children');
elements.familyStatusEligible.checked=true;
rows=build();
const family=byId(rows,'family');
verify(!!family,'family info rendered');
verify(family.title==='Πιστοποιητικό οικογενειακής κατάστασης','concise document title');
verify(window.EducationTransferDocuments.submissionChannel(family).text.includes('Αυτεπάγγελτα από ΔΔΕ'),'explicit visible submission status below title');
verify(family.tag.includes('δεν προσκομίζεται'),'not user-submitted');
verify(family.detail.includes('ΥΠΟΧΡΕΩΤΙΚΑ'),'binding duty');
verify(family.detail.includes('ΔΔΕ'),'responsible service');
verify(family.detail.includes('ν. 5099/2024'),'legal grounding');
verify(!family.detail.includes('Διαπιστώστε αν'),'no ambiguity');
verify(!byId(rows,'children-specific'),'no children special row merely from marriage');
elements.familyStatusEligible.checked=false;
elements.eligibleChildren.value='2';
rows=build();
verify(!!byId(rows,'family'),'family certificate for children');
const children=byId(rows,'children-specific');
verify(!!children,'conditional additional documents');
verify(children.detail.includes('βεβαίωση σπουδών'),'students documents');
verify(children.detail.includes('εφόσον συντρέχει'),'conditional not blanket');
verify(children.detail.includes('αλλοδαπών αρχών'),'foreign caveat');
elements.eligibleChildren.value='0';
rows=build();
verify(!byId(rows,'family') && !byId(rows,'children-specific'),'remove entries when criteria deselected');
const source=fs.readFileSync(path.join(__dirname,'../includes/transfer-documents.js'),'utf8');
verify(!source.includes('Έλεγχος αναζήτησης'),'old uncertain tag removed');
console.log(`PASS transfer family certificate ex officio: ${checks} checks`);
